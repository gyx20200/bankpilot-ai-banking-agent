-- D14 isolated test-only H2 extension. Global schema.sql and data.sql provide demo users/accounts.
CREATE TABLE IF NOT EXISTS demo_virtual_cards (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,account_id BIGINT NOT NULL, card_alias VARCHAR(32) UNIQUE NOT NULL,
 card_type VARCHAR(24) NOT NULL,status VARCHAR(16) NOT NULL,
 daily_ceiling DECIMAL(18,2) NOT NULL,single_tx_limit DECIMAL(18,2) NOT NULL,
 online_enabled BOOLEAN NOT NULL,issued_at TIMESTAMP NOT NULL,
 UNIQUE(user_id)
);
CREATE TABLE IF NOT EXISTS demo_card_applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,account_id BIGINT NOT NULL,request_id VARCHAR(64) NOT NULL,
 card_type VARCHAR(24) NOT NULL,status VARCHAR(24) NOT NULL,card_id BIGINT,
 created_at TIMESTAMP NOT NULL,updated_at TIMESTAMP NOT NULL,
 UNIQUE(user_id,request_id)
);
CREATE TABLE IF NOT EXISTS demo_card_limit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,card_id BIGINT NOT NULL,request_id VARCHAR(64) NOT NULL,
 old_single_limit DECIMAL(18,2) NOT NULL,new_single_limit DECIMAL(18,2) NOT NULL,
 disable_online BOOLEAN NOT NULL,created_at TIMESTAMP NOT NULL,
 UNIQUE(user_id,request_id)
);
