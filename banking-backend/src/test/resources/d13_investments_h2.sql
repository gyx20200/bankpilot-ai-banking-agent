-- Dedicated H2 test extension. Intentionally not part of global schema.sql.
CREATE TABLE IF NOT EXISTS investment_products (
 id BIGINT PRIMARY KEY, code VARCHAR(32) UNIQUE NOT NULL, name VARCHAR(100) UNIQUE NOT NULL,
 risk_level INT NOT NULL, nav DECIMAL(18,2) NOT NULL, active BOOLEAN NOT NULL,
 description VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS investment_profiles (
 user_id BIGINT PRIMARY KEY, risk_level INT NOT NULL, assessed_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS investment_positions (
 user_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 units DECIMAL(18,2) NOT NULL, cost_basis DECIMAL(18,2) NOT NULL,
 PRIMARY KEY(user_id,product_id)
);
CREATE TABLE IF NOT EXISTS investment_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL, account_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 action VARCHAR(10) NOT NULL, units DECIMAL(18,2) NOT NULL,
 nav_snapshot DECIMAL(18,2) NOT NULL, amount DECIMAL(18,2) NOT NULL,
 risk_snapshot INT NOT NULL, request_id VARCHAR(64) NOT NULL,
 status VARCHAR(24) NOT NULL, created_at TIMESTAMP NOT NULL,
 updated_at TIMESTAMP NOT NULL, UNIQUE(user_id,request_id)
);
CREATE TABLE IF NOT EXISTS investment_ledger (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT UNIQUE NOT NULL, user_id BIGINT NOT NULL, account_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL, action VARCHAR(10) NOT NULL,
 cash_delta DECIMAL(18,2) NOT NULL, units_delta DECIMAL(18,2) NOT NULL,
 created_at TIMESTAMP NOT NULL
);
