CREATE TABLE users (
  id BIGINT PRIMARY KEY,
  display_name VARCHAR(80) NOT NULL
);
CREATE TABLE accounts (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  account_no VARCHAR(32) NOT NULL UNIQUE,
  balance DECIMAL(18,2) NOT NULL,
  status VARCHAR(20) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE transactions (
  id BIGINT PRIMARY KEY,
  account_id BIGINT NOT NULL,
  direction VARCHAR(10) NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  category VARCHAR(50) NOT NULL,
  merchant_name VARCHAR(100),
  description VARCHAR(255),
  occurred_at TIMESTAMP NOT NULL,
  FOREIGN KEY (account_id) REFERENCES accounts(id)
);
CREATE TABLE payees (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  payee_name VARCHAR(100) NOT NULL,
  payee_account_id BIGINT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (payee_account_id) REFERENCES accounts(id)
);
CREATE TABLE subscriptions (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  merchant_name VARCHAR(100) NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  billing_cycle VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL,
  next_pay_date DATE
);

CREATE TABLE transfer_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  sender_account_id BIGINT NOT NULL,
  payee_id BIGINT NOT NULL,
  receiver_account_id BIGINT NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  remark VARCHAR(80) NOT NULL,
  request_id VARCHAR(64) NOT NULL,
  risk_level VARCHAR(10) NOT NULL,
  status VARCHAR(24) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  UNIQUE(user_id,request_id),
  FOREIGN KEY(user_id) REFERENCES users(id),
  FOREIGN KEY(sender_account_id) REFERENCES accounts(id),
  FOREIGN KEY(payee_id) REFERENCES payees(id),
  FOREIGN KEY(receiver_account_id) REFERENCES accounts(id)
);
CREATE TABLE approval_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  auth_method VARCHAR(20) NOT NULL,
  approval_status VARCHAR(16) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  expires_at TIMESTAMP,
  FOREIGN KEY(order_id) REFERENCES transfer_orders(id),
  FOREIGN KEY(user_id) REFERENCES users(id)
);
