-- Supplementary test schema for Day6 JUnit only. Old Day5 schema.sql is unchanged.
-- Day5 sample H2 schema omits cancelled_at even though real MySQL Day2 includes it.
ALTER TABLE subscriptions ADD COLUMN IF NOT EXISTS cancelled_at TIMESTAMP;
CREATE TABLE IF NOT EXISTS subscription_cancel_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  subscription_id BIGINT NOT NULL,
  request_id VARCHAR(64) NOT NULL,
  workflow_id VARCHAR(64),
  merchant_name VARCHAR(100) NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  billing_cycle VARCHAR(20) NOT NULL,
  status VARCHAR(24) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  authorized_at TIMESTAMP,
  executed_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  FOREIGN KEY(user_id) REFERENCES users(id),
  FOREIGN KEY(subscription_id) REFERENCES subscriptions(id),
  CONSTRAINT uk_sco_user_request UNIQUE(user_id,request_id)
);
CREATE TABLE IF NOT EXISTS subscription_cancel_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  action VARCHAR(30) NOT NULL,
  result VARCHAR(30) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  FOREIGN KEY(order_id) REFERENCES subscription_cancel_orders(id),
  FOREIGN KEY(user_id) REFERENCES users(id)
);
