package com.bankpilot.demo;

import static org.junit.jupiter.api.Assertions.*;

import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.springframework.web.server.ResponseStatusException;

/** H2 test with genuine Spring transactions, no real simulated-bank writes. */
class WorkflowRecoveryServiceTest {
    private static final String KEY = "d6-test-internal-agent-key-0123456789abcdef";
    private AnnotationConfigApplicationContext context;
    private JdbcTemplate jdbc;
    private WorkflowSessionService registry;
    private WorkflowRecoveryService recovery;
    private String thread;

    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement(proxyTargetClass = true)
    static class TestConfig {
        @Bean DriverManagerDataSource dataSource() {
            return new DriverManagerDataSource("jdbc:h2:mem:d6_"
                    + UUID.randomUUID().toString().replace("-", "")
                    + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        }
        @Bean JdbcTemplate jdbcTemplate(DriverManagerDataSource ds) { return new JdbcTemplate(ds); }
        @Bean PlatformTransactionManager transactionManager(DriverManagerDataSource ds) {
            return new DataSourceTransactionManager(ds);
        }
        @Bean ConversationService conversations(JdbcTemplate jdbc) { return new ConversationService(jdbc); }
        @Bean WorkflowSessionService sessions(JdbcTemplate jdbc, ConversationService conversations) {
            return new WorkflowSessionService(jdbc, conversations, KEY);
        }
        @Bean WorkflowRecoveryService recovery(JdbcTemplate jdbc, WorkflowSessionService sessions) {
            return new WorkflowRecoveryService(jdbc, sessions);
        }
    }

    @BeforeEach
    void setup() {
        context = new AnnotationConfigApplicationContext(TestConfig.class);
        jdbc = context.getBean(JdbcTemplate.class);
        registry = context.getBean(WorkflowSessionService.class);
        recovery = context.getBean(WorkflowRecoveryService.class);
        jdbc.execute("""
                CREATE TABLE agent_conversations (
                    id CHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL,
                    title VARCHAR(100) NOT NULL, status VARCHAR(20) NOT NULL,
                    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
                    UNIQUE(id,user_id))
                """);
        jdbc.execute("""
                CREATE TABLE agent_messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    conversation_id CHAR(36) NOT NULL, role VARCHAR(20) NOT NULL,
                    content VARCHAR(2000) NOT NULL, request_id VARCHAR(64),
                    created_at TIMESTAMP(6) NOT NULL,
                    UNIQUE(conversation_id,request_id),
                    FOREIGN KEY(conversation_id) REFERENCES agent_conversations(id))
                """);
        jdbc.execute("""
                CREATE TABLE agent_workflow_sessions (
                    thread_id VARCHAR(128) PRIMARY KEY, conversation_id CHAR(36) NOT NULL,
                    source_request_id VARCHAR(64), user_id BIGINT NOT NULL,
                    workflow_id VARCHAR(64), status VARCHAR(32) NOT NULL,
                    created_at TIMESTAMP(6) NOT NULL, expires_at TIMESTAMP(6) NOT NULL,
                    UNIQUE(conversation_id,source_request_id),
                    FOREIGN KEY(conversation_id,user_id) REFERENCES agent_conversations(id,user_id))
                """);
        jdbc.execute("""
                CREATE TABLE agent_workflow_recovery_claims (
                    thread_id VARCHAR(128) PRIMARY KEY, user_id BIGINT NOT NULL,
                    action_id CHAR(36) NOT NULL UNIQUE,
                    checkpoint_id VARCHAR(128) NOT NULL,
                    approved BOOLEAN NOT NULL, status VARCHAR(20) NOT NULL,
                    created_at TIMESTAMP(6) NOT NULL,
                    finalized_at TIMESTAMP(6) NULL,
                    FOREIGN KEY(thread_id) REFERENCES agent_workflow_sessions(thread_id))
                """);
        var conversations = context.getBean(ConversationService.class);
        String conversationId = conversations.create(7L, "D6 recovery test").conversationId();
        String requestId = "d6-user-12345678";
        String message = "给李四转10元，备注D6测试";
        conversations.appendUserMessage(7L, conversationId, message, requestId);
        thread = UUID.randomUUID().toString();
        registry.register(7L, thread, conversationId, requestId, message);
        registry.updateStatus(7L, thread, "WAITING");
    }

    @AfterEach
    void cleanup() {
        if (context != null) {
            jdbc.execute("DROP ALL OBJECTS");
            context.close();
        }
    }

    private void expect(HttpStatus status, org.junit.jupiter.api.function.Executable task) {
        assertEquals(status, assertThrows(ResponseStatusException.class, task).getStatusCode());
    }

    private WorkflowRecoveryService.ClaimView claim(boolean approved) {
        return recovery.claim(7L, thread, UUID.randomUUID().toString(),
                UUID.randomUUID().toString(), approved);
    }

    @Test void approveAndFinalizeUpdatesWorkflowAtomically() {
        var first = claim(true);
        assertEquals("CLAIMED", first.status());
        assertTrue(first.approved());
        var finished = recovery.finalizeClaim(7L, thread, "COMPLETED");
        assertEquals("COMPLETED", finished.status());
        assertNotNull(finished.finalizedAt());
        assertEquals("COMPLETED", registry.get(7L, thread).status());
        assertEquals(finished, recovery.finalizeClaim(7L, thread, "COMPLETED"));
    }

    @Test void rejectionAndFinalizeCannotBecomeApproval() {
        claim(false);
        expect(HttpStatus.CONFLICT, () -> recovery.finalizeClaim(7L, thread, "COMPLETED"));
        assertEquals("REJECTED", recovery.finalizeClaim(7L, thread, "REJECTED").status());
        expect(HttpStatus.CONFLICT, () -> recovery.finalizeClaim(7L, thread, "COMPLETED"));
    }

    @Test void onlyOneClaimPerThreadEvenDifferentActionId() {
        claim(true);
        expect(HttpStatus.CONFLICT, () -> claim(true));
        expect(HttpStatus.CONFLICT, () -> claim(false));
        Long count = jdbc.queryForObject("SELECT COUNT(*) FROM agent_workflow_recovery_claims", Long.class);
        assertEquals(1L, count);
    }

    @Test void otherUserCannotClaimOrReadOrFinalize() {
        expect(HttpStatus.NOT_FOUND, () -> recovery.claim(8L, thread,
                UUID.randomUUID().toString(), UUID.randomUUID().toString(), true));
        claim(true);
        expect(HttpStatus.NOT_FOUND, () -> recovery.get(8L, thread));
        expect(HttpStatus.NOT_FOUND, () -> recovery.finalizeClaim(8L, thread, "COMPLETED"));
    }

    @Test void expiredWorkflowCannotClaimButCanFinishAlreadyClaimed() {
        jdbc.update("UPDATE agent_workflow_sessions SET expires_at=? WHERE thread_id=?",
                LocalDateTime.now(ZoneOffset.UTC).minusMinutes(1), thread);
        expect(HttpStatus.GONE, () -> claim(true));
    }

    @Test void cannotClaimCompletedWorkflow() {
        registry.updateStatus(7L, thread, "COMPLETED");
        expect(HttpStatus.CONFLICT, () -> claim(true));
    }

    @Test void unknownOutcomePermanentlyBlocksReplay() {
        claim(true);
        assertEquals("NOT_CONFIRMED", recovery.finalizeClaim(7L, thread, "NOT_CONFIRMED").status());
        assertEquals("NOT_CONFIRMED", registry.get(7L, thread).status());
        expect(HttpStatus.CONFLICT, () -> claim(true));
    }

    @Test void invalidInputsAndUnclaimedFinalizeAreRejected() {
        expect(HttpStatus.BAD_REQUEST, () -> recovery.claim(7L, thread,
                "wrong-id", UUID.randomUUID().toString(), true));
        expect(HttpStatus.BAD_REQUEST, () -> recovery.claim(7L, thread,
                UUID.randomUUID().toString(), "!unsafe", true));
        expect(HttpStatus.NOT_FOUND, () -> recovery.get(7L, thread));
        expect(HttpStatus.NOT_FOUND, () -> recovery.finalizeClaim(7L, thread, "COMPLETED"));
    }
}
