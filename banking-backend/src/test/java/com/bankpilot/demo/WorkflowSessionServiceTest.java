package com.bankpilot.demo;

import static org.junit.jupiter.api.Assertions.*;

import java.time.Duration;
import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.springframework.web.server.ResponseStatusException;

/** Isolated H2 test database, real Spring transaction proxies, no bank writes. */
class WorkflowSessionServiceTest {
    private static final String KEY = "test-d5-local-only-key-0123456789abcdef";
    private static final String REQUEST = "d5-source-123456";
    private static final String CONTENT = "查询我的余额";
    private AnnotationConfigApplicationContext context;
    private JdbcTemplate jdbc;
    private WorkflowSessionService service;
    private ConversationService conversations;
    private String conversationId;
    private String threadId;

    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement(proxyTargetClass = true)
    static class TestConfig {
        @Bean
        DriverManagerDataSource dataSource() {
            return new DriverManagerDataSource("jdbc:h2:mem:d5_"
                    + UUID.randomUUID().toString().replace("-", "")
                    + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        }
        @Bean
        JdbcTemplate jdbcTemplate(DriverManagerDataSource ds) {
            return new JdbcTemplate(ds);
        }
        @Bean
        PlatformTransactionManager transactionManager(DriverManagerDataSource ds) {
            return new DataSourceTransactionManager(ds);
        }
        @Bean
        ConversationService conversations(JdbcTemplate jdbc) {
            return new ConversationService(jdbc);
        }
        @Bean
        WorkflowSessionService workflowSessions(JdbcTemplate jdbc, ConversationService conversations) {
            return new WorkflowSessionService(jdbc, conversations, KEY);
        }
    }

    @BeforeEach
    void setup() {
        context = new AnnotationConfigApplicationContext(TestConfig.class);
        jdbc = context.getBean(JdbcTemplate.class);
        conversations = context.getBean(ConversationService.class);
        service = context.getBean(WorkflowSessionService.class);
        jdbc.execute("""
                CREATE TABLE agent_conversations (
                  id CHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL,
                  title VARCHAR(100) NOT NULL, status VARCHAR(20) NOT NULL,
                  created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
                  UNIQUE(id,user_id))
                """);
        jdbc.execute("""
                CREATE TABLE agent_messages (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  conversation_id CHAR(36) NOT NULL, role VARCHAR(20) NOT NULL,
                  content VARCHAR(2000) NOT NULL, request_id VARCHAR(64),
                  created_at TIMESTAMP(6) NOT NULL,
                  UNIQUE(conversation_id,request_id),
                  FOREIGN KEY(conversation_id) REFERENCES agent_conversations(id))
                """);
        jdbc.execute("""
                CREATE TABLE agent_workflow_sessions (
                  thread_id VARCHAR(128) PRIMARY KEY, conversation_id CHAR(36) NOT NULL,
                  source_request_id VARCHAR(64), user_id BIGINT NOT NULL,
                  workflow_id VARCHAR(64), status VARCHAR(32) NOT NULL,
                  created_at TIMESTAMP(6) NOT NULL, expires_at TIMESTAMP(6) NOT NULL,
                  UNIQUE(conversation_id,source_request_id),
                  FOREIGN KEY(conversation_id,user_id) REFERENCES agent_conversations(id,user_id))
                """);
        conversationId = conversations.create(7L, "D5 test").conversationId();
        conversations.appendUserMessage(7L, conversationId, CONTENT, REQUEST);
        threadId = UUID.randomUUID().toString();
    }

    @AfterEach
    void close() {
        if (context != null) {
            try {
                if (jdbc != null) jdbc.execute("DROP ALL OBJECTS");
            } finally {
                context.close();
            }
        }
    }

    private WorkflowSessionService.SessionView register() {
        return service.register(7L, threadId, conversationId, REQUEST, CONTENT);
    }

    private long count() {
        return jdbc.queryForObject("SELECT COUNT(*) FROM agent_workflow_sessions", Long.class);
    }

    private void expect(HttpStatus code, org.junit.jupiter.api.function.Executable action) {
        assertEquals(code, assertThrows(ResponseStatusException.class, action).getStatusCode());
    }

    @Test
    void registerGetAndListWithFixedUtcExpiry() {
        var row = register();
        assertEquals(threadId, row.threadId());
        assertEquals(conversationId, row.conversationId());
        assertEquals(REQUEST, row.sourceRequestId());
        assertEquals("RUNNING", row.status());
        assertEquals(Duration.ofMinutes(30), Duration.between(
                Instant.parse(row.createdAt()), Instant.parse(row.expiresAt())));
        assertEquals(row, service.get(7L, threadId));
        assertEquals(java.util.List.of(row), service.list(7L, conversationId, 20).items());
    }

    @Test
    void duplicateSourceOrThreadCannotRegisterAgain() {
        var original = register();
        expect(HttpStatus.CONFLICT, this::register);
        expect(HttpStatus.CONFLICT, () -> service.register(7L, UUID.randomUUID().toString(),
                conversationId, REQUEST, CONTENT));
        assertEquals(1L, count());
        assertEquals(original, service.get(7L, threadId));
    }

    @Test
    void enforceConversationAndThreadOwnership() {
        expect(HttpStatus.NOT_FOUND,
                () -> service.register(8L, threadId, conversationId, REQUEST, CONTENT));
        register();
        expect(HttpStatus.NOT_FOUND, () -> service.get(8L, threadId));
        expect(HttpStatus.NOT_FOUND, () -> service.list(8L, conversationId, 20));
        expect(HttpStatus.NOT_FOUND, () -> service.updateStatus(8L, threadId, "COMPLETED"));
        assertEquals("RUNNING", service.get(7L, threadId).status());
    }

    @Test
    void rejectMissingMismatchedOrAssistantSource() {
        expect(HttpStatus.CONFLICT, () -> service.register(7L, threadId, conversationId,
                "missing-123456", CONTENT));
        expect(HttpStatus.CONFLICT, () -> service.register(7L, threadId, conversationId,
                REQUEST, "查询交易记录"));
        conversations.appendAssistantMessage(7L, conversationId, "模拟余额回复",
                "asst-12345678", REQUEST, CONTENT);
        expect(HttpStatus.CONFLICT, () -> service.register(7L, threadId, conversationId,
                "asst-12345678", "模拟余额回复"));
        assertEquals(0L, count());
    }

    @Test
    void reuseD3MaskingAndSecretRejection() {
        String maskedRequest = "phone-12345678";
        String message = "查询手机号13800138000的收款人";
        var stored = conversations.appendUserMessage(7L, conversationId, message, maskedRequest);
        assertTrue(stored.message().content().contains("[手机号已脱敏]"));
        service.register(7L, threadId, conversationId, maskedRequest, message);
        expect(HttpStatus.UNPROCESSABLE_ENTITY, () -> service.register(7L,
                UUID.randomUUID().toString(), conversationId, REQUEST, "密码:123456"));
        assertEquals(1L, count());
    }

    @Test
    void lifecycleDoesNotExtendExpiryAndTerminalCannotReopen() {
        var original = register();
        var waiting = service.updateStatus(7L, threadId, "WAITING");
        assertEquals(original.expiresAt(), waiting.expiresAt());
        assertEquals(waiting, service.updateStatus(7L, threadId, "WAITING"));
        service.updateStatus(7L, threadId, "RUNNING");
        var completed = service.updateStatus(7L, threadId, "COMPLETED");
        assertEquals(completed, service.updateStatus(7L, threadId, "COMPLETED"));
        expect(HttpStatus.CONFLICT, () -> service.updateStatus(7L, threadId, "RUNNING"));
        expect(HttpStatus.CONFLICT, () -> service.updateStatus(7L, threadId, "REJECTED"));
    }

    @Test
    void expiredSessionReadableButCannotTransition() {
        register();
        jdbc.update("UPDATE agent_workflow_sessions SET expires_at=? WHERE thread_id=?",
                LocalDateTime.now(ZoneOffset.UTC).minusMinutes(1), threadId);
        var expired = service.get(7L, threadId);
        assertTrue(Instant.parse(expired.expiresAt()).isBefore(Instant.now()));
        expect(HttpStatus.GONE, () -> service.updateStatus(7L, threadId, "WAITING"));
        assertEquals(expired, service.updateStatus(7L, threadId, "RUNNING"));
    }

    @Test
    void validateInputsAndTrustedServiceKey() {
        service.requireTrustedAgent(KEY);
        expect(HttpStatus.FORBIDDEN, () -> service.requireTrustedAgent(null));
        expect(HttpStatus.FORBIDDEN, () -> service.requireTrustedAgent("wrong"));
        var unconfigured = new WorkflowSessionService(jdbc, conversations, "");
        expect(HttpStatus.SERVICE_UNAVAILABLE, () -> unconfigured.requireTrustedAgent(KEY));
        expect(HttpStatus.BAD_REQUEST, () -> service.get(7L, "not-a-uuid"));
        expect(HttpStatus.BAD_REQUEST, () -> service.list(7L, conversationId, 101));
        expect(HttpStatus.BAD_REQUEST, () -> service.updateStatus(7L, threadId, "SUCCESS"));
    }
}
