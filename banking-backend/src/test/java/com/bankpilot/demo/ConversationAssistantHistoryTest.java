package com.bankpilot.demo;

import static org.junit.jupiter.api.Assertions.*;

import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.web.server.ResponseStatusException;

/** Isolated D3 service tests with H2. Real MySQL still requires E2E verification. */
class ConversationAssistantHistoryTest {
    private JdbcTemplate jdbc;
    private ConversationService service;
    private String conversationId;

    @BeforeEach
    void setup() {
        var dbName = "d3assistant_" + UUID.randomUUID().toString().replace("-", "");
        var ds = new DriverManagerDataSource(
                "jdbc:h2:mem:" + dbName + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("""
                CREATE TABLE agent_conversations (
                  id CHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL,
                  title VARCHAR(100) NOT NULL, status VARCHAR(20) NOT NULL,
                  created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL)
                """);
        jdbc.execute("""
                CREATE TABLE agent_messages (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  conversation_id CHAR(36) NOT NULL, role VARCHAR(20) NOT NULL,
                  content VARCHAR(2000) NOT NULL, request_id VARCHAR(64),
                  created_at TIMESTAMP NOT NULL,
                  CONSTRAINT uq_message_idempotent UNIQUE(conversation_id, request_id))
                """);
        conversationId = UUID.randomUUID().toString();
        var now = Timestamp.valueOf(LocalDateTime.now());
        jdbc.update("""
                INSERT INTO agent_conversations
                    (id,user_id,title,status,created_at,updated_at)
                VALUES (?,?,?,'ACTIVE',?,?)
                """, conversationId, 7L, "test", now, now);
        service = new ConversationService(jdbc);
    }

    @Test
    void onlyRespondToExistingMatchingUserRequestAndDeduplicate() {
        var user = service.appendUserMessage(7L, conversationId,
                "查询我的余额", "request-123456");
        assertTrue(user.created());
        var reply = service.appendAssistantMessage(7L, conversationId,
                "模拟银行当时余额 ¥100.00。", "asst-12345678",
                "request-123456", "查询我的余额");
        assertTrue(reply.created());
        assertEquals("ASSISTANT", reply.message().role());

        var repeated = service.appendAssistantMessage(7L, conversationId,
                "模拟银行当时余额 ¥100.00。", "asst-12345678",
                "request-123456", "查询我的余额");
        assertFalse(repeated.created());
        assertEquals(reply.message().messageId(), repeated.message().messageId());
        assertEquals(2, service.messages(7L, conversationId, 20, null).items().size());
    }

    @Test
    void rejectAssistantWhenOriginalUserContentDoesNotMatch() {
        service.appendUserMessage(7L, conversationId, "查询我的余额", "request-123456");
        var error = assertThrows(ResponseStatusException.class,
                () -> service.appendAssistantMessage(7L, conversationId,
                    "已经转账成功", "asst-12345678",
                    "request-123456", "帮我转账"));
        assertEquals(HttpStatus.CONFLICT, error.getStatusCode());
    }

    @Test
    void rejectOtherUsersConversation() {
        service.appendUserMessage(7L, conversationId, "查询我的余额", "request-123456");
        var error = assertThrows(ResponseStatusException.class,
                () -> service.appendAssistantMessage(8L, conversationId,
                    "模拟银行当时余额 ¥100.00。", "asst-12345678",
                    "request-123456", "查询我的余额"));
        assertEquals(HttpStatus.NOT_FOUND, error.getStatusCode());
    }

    @Test
    void rejectConflictingAssistantRequestId() {
        service.appendUserMessage(7L, conversationId, "查询我的余额", "request-123456");
        service.appendAssistantMessage(7L, conversationId,
                "第一次回复", "asst-12345678", "request-123456", "查询我的余额");
        var error = assertThrows(ResponseStatusException.class,
                () -> service.appendAssistantMessage(7L, conversationId,
                    "篡改后的回复", "asst-12345678", "request-123456", "查询我的余额"));
        assertEquals(HttpStatus.CONFLICT, error.getStatusCode());
    }
}
