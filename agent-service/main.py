"""BankPilot Day 2: FastAPI orchestration, READ ONLY, no LLM yet."""

from typing import Any
from uuid import uuid4
from decimal import Decimal, InvalidOperation
import logging

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from app.router import Intent, parse_intent
from app.banking_client import (
    BankingServiceError,
    BANK_API_MODE,
    get_balance,
    get_transactions,
    get_payees,
    get_subscriptions,
)

app = FastAPI(title="BankPilot Agent Gateway - Day 2", version="0.2.0")
log = logging.getLogger("bankpilot.agent")


class ChatRequest(BaseModel):
    message: str = Field(min_length=1, max_length=300)


class ChatResponse(BaseModel):
    reply: str
    intent: Intent
    data: Any = None
    source: str = "none"
    requestId: str


def format_money(value: Any) -> str:
    try:
        return f"{Decimal(str(value)):,.2f}"
    except (InvalidOperation, ValueError):
        return "金额格式异常"


@app.get("/health")
@app.get("/api/agent/health")
async def health():
    return {"status": "ok", "service": "agent-gateway", "mode": "rules-day2-read-only"}


@app.post("/api/agent/chat", response_model=ChatResponse)
async def chat(request: ChatRequest):
    request_id = uuid4().hex[:12]
    intent = parse_intent(request.message)
    log.info("request_id=%s intent=%s", request_id, intent)  # Do not log account data or full message.

    if intent == "unsupported":
        return ChatResponse(
            reply="目前支持：查询余额、最近交易、常用收款人、订阅代扣。转账和复合任务会在后续版本开放。",
            intent=intent, requestId=request_id,
        )

    try:
        if intent == "balance":
            data = await get_balance()
            reply = (
                f"{data.get('userName', '您好')}，您的模拟账户 "
                f"{data.get('accountNoMasked', '****')} 当前余额为 ¥{format_money(data['balance'])}。"
            )
        elif intent == "transactions":
            data = await get_transactions()
            reply = f"已从银行查询接口获取 {len(data)} 条交易流水（最多 100 条），详见下方列表。"
        elif intent == "payees":
            data = await get_payees()
            reply = f"当前共有 {len(data)} 位常用收款人，详见下方列表。"
        else:
            data = await get_subscriptions()
            reply = f"查询到 {len(data)} 条代扣协议；本阶段仅支持查询，不会自动取消。"
    except BankingServiceError as exc:
        log.warning("request_id=%s backend_unavailable", request_id)
        raise HTTPException(status_code=502, detail=str(exc)) from exc

    # The data is read directly from the banking API, not generated by a model.
    return ChatResponse(reply=reply, intent=intent, data=data, source=("mock-api" if BANK_API_MODE == "mock" else "bank-api"), requestId=request_id)
